import os
import csv

input_file = "data/shift_log.txt"
report_file = "data/report.txt"
reject_file = "data/rejects.csv"

os.makedirs("data", exist_ok=True)

valid_records = []
rejected_records = []

with open(input_file, "r") as file:
    lines = file.readlines()

for line_number, line in enumerate(lines, start=1):
    line = line.strip()

    if not line:
        rejected_records.append([line_number, line, "Empty line"])
        continue

    fields = [field.strip() for field in line.split(",")]

    if len(fields) != 3:
        rejected_records.append([line_number, line, "Incorrect number of fields"])
        continue

    work_order, description, status = fields

    if not work_order.startswith("WO") or not work_order[2:].isdigit():
        rejected_records.append([line_number, line, "Invalid work order"])
        continue

    if not description:
        rejected_records.append([line_number, line, "Missing description"])
        continue

    if status not in ["Completed", "Pending", "Failed"]:
        rejected_records.append([line_number, line, "Invalid status"])
        continue

    if any(word in description.lower() for word in ["filthy", "sludge", "rotten"]):
        rejected_records.append([line_number, line, "Filthy or contaminated work area"])
        continue

    valid_records.append([work_order, description, status])

total = len(valid_records)
completed = sum(1 for record in valid_records if record[2] == "Completed")
pending = sum(1 for record in valid_records if record[2] == "Pending")
failed = sum(1 for record in valid_records if record[2] == "Failed")

with open(report_file, "w") as file:
    file.write("SHIFT LOG REPORT\n")
    file.write("=" * 75 + "\n")
    file.write(f"{'WORK ORDER':<15}{'DESCRIPTION':<40}{'STATUS':<15}\n")
    file.write("-" * 75 + "\n")

    for record in valid_records:
        file.write(f"{record[0]:<15}{record[1]:<40}{record[2]:<15}\n")

    file.write("-" * 75 + "\n")
    file.write(f"Total valid records : {total}\n")
    file.write(f"Completed           : {completed}\n")
    file.write(f"Pending             : {pending}\n")
    file.write(f"Failed              : {failed}\n")
    file.write(f"Rejected            : {len(rejected_records)}\n")

with open(reject_file, "w", newline="") as file:
    writer = csv.writer(file)
    writer.writerow(["Line Number", "Rejected Line", "Reason"])
    writer.writerows(rejected_records)

print("Processing completed.")
