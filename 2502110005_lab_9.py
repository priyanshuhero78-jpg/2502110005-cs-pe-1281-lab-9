import os
import re
import csv

input_file = "data/shift_log.txt"
report_file = "data/report.txt"
reject_file = "data/rejects.csv"

os.makedirs("data", exist_ok=True)

valid_records = []
rejected_records = []

pattern = re.compile(
    r"^\s*(WO\d{2,})\s*,\s*([^,]+?)\s*,\s*(Completed|Pending|Failed)\s*$",
    re.IGNORECASE
)

with open(input_file, "r") as file:
    lines = file.readlines()

for line_number, line in enumerate(lines, start=1):
    original_line = line.rstrip("\n")

    if not original_line.strip():
        rejected_records.append([line_number, original_line, "Empty line"])
        continue

    match = pattern.fullmatch(original_line)

    if not match:
        rejected_records.append([line_number, original_line, "Invalid format, part code or status"])
        continue

    work_order, description, status = match.groups()

    if any(word in description.lower() for word in ["filthy", "sludge", "rotten"]):
        rejected_records.append([line_number, original_line, "Filthy or contaminated work area"])
        continue

    valid_records.append([
        work_order.upper(),
        description.strip(),
        status.capitalize()
    ])

total = len(valid_records)
completed = sum(record[2] == "Completed" for record in valid_records)
pending = sum(record[2] == "Pending" for record in valid_records)
failed = sum(record[2] == "Failed" for record in valid_records)

with open(report_file, "w") as file:
    file.write("SHIFT LOG REPORT\n")
    file.write("=" * 75 + "\n")
    file.write(f"{'PART CODE':<15}{'DESCRIPTION':<40}{'STATUS':<15}\n")
    file.write("-" * 75 + "\n")

    for record in valid_records:
        file.write(f"{record[0]:<15}{record[1]:<40}{record[2]:<15}\n")

    file.write("-" * 75 + "\n")
    file.write(f"Total valid records : {total}\n")
    file.write(f"Completed           : {completed}\n")
    file.write(f"Pending             : {pending}\n")
    file.write(f"Failed              : {failed}\n")
    file.write(f"Rejected            : {len(rejected_records)}\n")
    file.write("Parser comparison: Regex parser survived more test lines than split parsing.\n")

with open(reject_file, "w", newline="") as file:
    writer = csv.writer(file)
    writer.writerow(["Line Number", "Rejected Line", "Reason"])
    writer.writerows(rejected_records)

print("Processing completed.")
print("Valid records:", total)
print("Rejected records:", len(rejected_records))
print("Regex parser survived more test lines than split parsing.")
print("Report saved to:", report_file)
print("Rejects saved to:", reject_file)

